#!/usr/bin/env python3
"""Writes Resources/web/components/manifest.js: every module under components/ (sorted, tools last), and for modules
whose first lines carry `// @lazy`, the component names they define (from defineComponent / registerFence literals), so
the core loads them on first use. Run after adding or renaming a component module; a unit test checks it is current.

    python3 scripts/gen-web-manifest.py            # write
    python3 scripts/gen-web-manifest.py --check    # exit 1 when the file on disk is stale
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "Resources", "web")
COMPONENTS = os.path.join(WEB, "components")
OUT = os.path.join(COMPONENTS, "manifest.js")
NAMES = re.compile(r"(?:defineComponent\(\s*\{\s*names?\s*:|registerFence\()\s*(\[[^\]]*\]|'[^']*'|\"[^\"]*\")")


def names_in(src):
    out = []
    for m in NAMES.finditer(src):
        lit = m.group(1)
        vals = re.findall(r"'([^']*)'|\"([^\"]*)\"", lit)
        out += [a or b for a, b in vals]
    seen = set()
    return [n for n in out if not (n in seen or seen.add(n))]


def modules():
    files = []
    for dirpath, _, names in os.walk(COMPONENTS):
        for n in names:
            if n.endswith(".js") and n != "manifest.js":
                files.append(os.path.relpath(os.path.join(dirpath, n), WEB))
    # Components first (alphabetical), tool descriptors after them: a tool body may use a component.
    files.sort(key=lambda p: (p.count("/"), p))
    mods = []
    for rel in files:
        with open(os.path.join(WEB, rel), encoding="utf-8") as f:
            src = f.read()
        head = "\n".join(src.splitlines()[:5])
        entry = {"src": rel}
        if re.search(r"^//\s*@lazy\b", head, re.M):
            entry["lazy"] = names_in(src)
            if not entry["lazy"]:
                sys.exit(f"{rel} is marked @lazy but defines no component names")
        mods.append(entry)
    return mods


def render(mods):
    lines = ["// Generated by scripts/gen-web-manifest.py from the files under components/ — do not edit by hand.",
             "window.TeacherManifest = { version: 1, modules: ["]
    for m in mods:
        lines.append("  " + json.dumps(m, ensure_ascii=False).replace('"src"', "src").replace('"lazy"', "lazy") + ",")
    lines.append("] };")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render(modules())
    current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in sys.argv:
        if current != text:
            sys.exit("components/manifest.js is stale: run scripts/gen-web-manifest.py")
        print("manifest is current")
    else:
        if current != text:
            with open(OUT, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote " + os.path.relpath(OUT, ROOT))
        else:
            print("manifest unchanged")
